const fs=require('node:fs')
const cp=require('node:child_process')
const os=require('node:os')
const path=require('node:path')
const userData=fs.mkdtempSync(path.join(os.tmpdir(),'pt006-context-ui-'))
const binary='C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'
const edge=cp.spawn(binary,['--headless=new','--disable-gpu','--no-first-run','--remote-debugging-port=0','--user-data-dir='+userData,'about:blank'],{stdio:['ignore','ignore','pipe']})
let ws,seq=0
const pending=new Map(),errors=[]
const timeout=setTimeout(()=>{edge.kill();console.error('Context UI timeout');process.exit(2)},75000)
async function connect(){
  const address=await new Promise((resolve,reject)=>{
    let output=''
    edge.stderr.on('data',data=>{output+=data.toString();const m=output.match(/DevTools listening on (ws:\/\/[^\s]+)/);if(m)resolve(m[1])})
    edge.on('error',reject)
    edge.on('exit',code=>reject(Error('Edge exited '+code)))
  })
  const tabs=await(await fetch('http://'+new URL(address).host+'/json/list')).json()
  ws=new WebSocket(tabs.find(t=>t.type==='page').webSocketDebuggerUrl)
  await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject})
  ws.onmessage=event=>{
    const v=JSON.parse(event.data)
    if(v.method==='Runtime.exceptionThrown')errors.push(v.params.exceptionDetails?.exception?.description??'Browser exception')
    const pendingCall=pending.get(v.id)
    if(pendingCall){pending.delete(v.id);if(v.error)pendingCall.reject(Error(JSON.stringify(v.error)));else pendingCall.resolve(v.result)}
  }
}
const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}))})
async function evaluate(expression){
  const res=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true})
  if(res.exceptionDetails)throw Error(res.exceptionDetails.exception?.description??res.exceptionDetails.text)
  return res.result.value
}
